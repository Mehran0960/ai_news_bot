def _api_product_url(obj):
    # Never synthesize a product URL from a generic numeric "id": API payloads
    # also contain category, seller, campaign, and recommendation IDs.
    for key in ("url", "product_url", "web_url", "canonical_url", "productUrl"):
        raw = obj.get(key)
        if isinstance(raw, dict):
            raw = raw.get("uri") or raw.get("url") or ""
        if isinstance(raw, str):
            candidate = safe_product_url(urljoin("https://www.digikala.com/", raw))
            if candidate:
                return candidate
    return ""


def api_search_product_urls(payload):
    """Read the product array only; never confuse filter/category IDs with product IDs."""
    data = payload.get("data", {}) if isinstance(payload, dict) else {}
    product_items = data.get("products", []) if isinstance(data, dict) else []
    found = []
    for obj in product_items if isinstance(product_items, list) else []:
        if not isinstance(obj, dict):
            continue
        title = obj.get("title_fa") or obj.get("product_title") or obj.get("title")
        raw_id = obj.get("id") or obj.get("product_id")
        product_shape = any(k in obj for k in ("default_variant", "variants", "images", "product_type", "status"))
        if not title or not product_shape:
            continue
        candidate = _api_product_url(obj)
        if not candidate and (isinstance(raw_id, int) or (isinstance(raw_id, str) and raw_id.isdigit())):
            candidate = safe_product_url(f"https://www.digikala.com/product/dkp-{int(raw_id)}/")
        if candidate and candidate not in found:
            found.append(candidate)
        if len(found) >= MAX_PER_QUERY:
            break
    return found


def _offer_discount_percent(obj: dict) -> int:
    """Get the retailer-declared discount or derive one from current/list prices."""
    sources = []
    if isinstance(obj.get("price"), dict):
        sources.append(obj["price"])
    variant = obj.get("default_variant")
    if isinstance(variant, dict) and isinstance(variant.get("price"), dict):
        sources.append(variant["price"])
    sources.append(obj)
    for source in sources:
        raw = source.get("discount_percent")
        try:
            discount = int(float(normalize_digits(str(raw))))
            if 0 < discount <= 100:
                return discount
        except (TypeError, ValueError, OverflowError):
            pass
        current = None
        original = None
        for key in ("selling_price_toman", "selling_price_tooman", "price_toman"):
            if source.get(key) is not None:
                current = _money_to_toman(source[key], "IRT")
                if current:
                    break
        if current is None:
            for key in ("selling_price", "selling_price_rial", "price"):
                if source.get(key) is not None:
                    current = _money_to_toman(source[key], "IRR")
                    if current:
                        break
        for key in ("rrp_price_toman", "original_price_toman", "list_price_toman"):
            if source.get(key) is not None:
                original = _money_to_toman(source[key], "IRT")
                if original:
                    break
        if original is None:
            for key in ("rrp_price", "rrp_price_rial", "original_price", "regular_price"):
                if source.get(key) is not None:
                    original = _money_to_toman(source[key], "IRR")
                    if original:
                        break
        if current and original and original > current:
            return max(1, min(100, round(100 * (original - current) / original)))
    return 0


