def score_product(p: dict) -> dict:
    # Category is retained for diagnostics only; it never adds or subtracts ranking points.
    category = classify_category(p.get("title", ""))
    score = 0
    price = p.get("current_price")
    if price:
        if price <= 500_000:
            score += 24
        elif price <= 1_000_000:
            score += 22
        elif price <= 2_000_000:
            score += 18
        elif price <= 5_000_000:
            score += 13
        elif price <= 10_000_000:
            score += 8
        else:
            score += 3

    original = p.get("original_price")
    if original and price and original > price:
        discount = round(100 * (original - price) / original)
        p["discount_percent"] = max(0, min(100, discount))
        p["savings_toman"] = int(original - price)
    else:
        p["discount_percent"] = 0
        p["savings_toman"] = 0

    rating = p.get("rating")
    if rating is not None:
        if rating >= 4.5:
            score += 12
        elif rating >= 4.0:
            score += 9
        elif rating >= 3.5:
            score += 5
        elif rating < 3.0:
            score -= 5

    reviews = max(0, int(p.get("review_count") or 0))
    # Review volume and rating are popularity proxies, used only after discount and saving.
    score += min(30, round(3.5 * math.log1p(reviews)))
    if p.get("image_url"):
        score += 4
    if not price:
        score -= 12

    discount_pct = int(p.get("discount_percent") or 0)
    savings = int(p.get("savings_toman") or 0)
    savings_score = min(20, round(3.0 * math.log1p(savings / 100_000))) if savings else 0
    review_score = min(10, round(1.5 * math.log1p(reviews))) if reviews else 0
    rating_score = max(0, min(5, round((float(rating) - 3.0) * 2))) if rating is not None else 0

    p["category"] = category
    p["demand_score"] = max(0, min(100, int(score)))
    p["promo_score"] = max(0, min(100, int(discount_pct * 0.65 + savings_score + review_score + rating_score)))
    p["qualifies_as_deal"] = bool(
        discount_pct >= MIN_DISCOUNT_PERCENT and savings >= MIN_SAVINGS_TOMAN
    )
    return p


def deal_sort_key(p: dict) -> tuple:
    """Listed discount and cash saving lead; verified market value and popularity break ties."""
    verified_median = (
        p.get("market_status") == "verified"
        and p.get("market_reference_kind") == "seller_median"
        and p.get("market_price_advantage_pct") is not None
    )
    market_known = 1 if verified_median else 0
    market_advantage = int(p.get("market_price_advantage_pct") or 0) if verified_median else -101
    return (
        int(p.get("discount_percent") or 0),
        int(p.get("savings_toman") or 0),
        market_known,
        market_advantage,
        int(p.get("click_count_30d") or 0),
        int(p.get("demand_score") or 0),
        int(p.get("review_count") or 0),
    )


def fetch_click_statistics() -> dict[str, int]:
    """Fetch aggregate last-30-day clicks; analytics outages never block publication."""
    base = AFFILIO_CLICK_TRACKER_BASE_URL.strip().rstrip("/")
    if not base.startswith("https://"):
        print("CLICK_STATS_UNAVAILABLE reason=tracker_url_not_https")
        return {}
    try:
        response = SESSION.get(
            f"{base}/stats",
            headers={"Accept": "application/json", "User-Agent": "AffilioRadarAnalytics/1.0"},
            timeout=(4, 8),
        )
        response.raise_for_status()
        payload = response.json()
        products = payload.get("products") if isinstance(payload, dict) else None
        # Ignore partial snapshots so a truncated day's results cannot distort rankings.
        if payload.get("ok") is not True or payload.get("complete") is not True or not isinstance(products, dict):
            print("CLICK_STATS_UNAVAILABLE reason=incomplete_or_invalid_snapshot")
            return {}
        counts = {}
        for pid, raw_count in products.items():
            if not re.fullmatch(r"dkp-\d{1,12}", str(pid)):
                continue
            try:
                count = int(raw_count)
            except (TypeError, ValueError, OverflowError):
                continue
            if count >= 0:
                counts[str(pid)] = count
        print(
            f"CLICK_STATS_LOADED days={payload.get('days', 30)} "
            f"products={len(counts)} total_clicks={int(payload.get('totalClicks') or 0)} "
            f"updated_at={payload.get('updatedAt', 'unknown')}"
        )
        return counts
    except Exception as exc:
        print(f"CLICK_STATS_UNAVAILABLE error={type(exc).__name__}")
        return {}


def enrich_click_statistics(products: list[dict]) -> None:
    """Attach valid aggregate click counts for tie-breaking, never as a hard publish filter."""
    counts = fetch_click_statistics()
    for product in products:
        pid = str(product.get("product_id") or product_id(product.get("product_url", "")))
        product["click_count_30d"] = counts.get(pid, 0)


