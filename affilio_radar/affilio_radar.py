def gregorian_to_jalali(gy: int, gm: int, gd: int) -> tuple[int, int, int]:
    """Convert a Gregorian calendar date to the Solar Hijri (Jalali) calendar."""
    g_days_before_month = (0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334)
    if not 1 <= gm <= 12 or not 1 <= gd <= 31:
        raise ValueError("Invalid Gregorian month or day")
    if gy > 1600:
        jy = 979
        gy -= 1600
    else:
        jy = 0
        gy -= 621
    gy2 = gy + 1 if gm > 2 else gy
    days = (
        365 * gy
        + (gy2 + 3) // 4
        - (gy2 + 99) // 100
        + (gy2 + 399) // 400
        - 80
        + gd
        + g_days_before_month[gm - 1]
    )
    jy += 33 * (days // 12053)
    days %= 12053
    jy += 4 * (days // 1461)
    days %= 1461
    if days > 365:
        jy += (days - 1) // 365
        days = (days - 1) % 365
    if days < 186:
        jm = 1 + days // 31
        jd = 1 + days % 31
    else:
        jm = 7 + (days - 186) // 30
        jd = 1 + (days - 186) % 30
    return jy, jm, jd


def format_deal_expiry(value) -> str:
    """Format a confirmed deal deadline as a Persian date and Iran-local time."""
    raw = str(value or "").strip()
    if not raw:
        return ""
    try:
        parsed = datetime.fromisoformat(raw.replace("Z", "+00:00"))
        if parsed.tzinfo is None:
            parsed = parsed.replace(tzinfo=timezone.utc)
        try:
            from zoneinfo import ZoneInfo
            local = parsed.astimezone(ZoneInfo("Asia/Tehran"))
        except Exception:
            local = parsed.astimezone(timezone(timedelta(hours=3, minutes=30)))
        # For display only, represent an exact midnight cutoff as the preceding
        # calendar day at 23:59, which is clearer for Persian-language audiences.
        if local.hour == 0 and local.minute == 0:
            local -= timedelta(minutes=1)
        jalali_year, jalali_month, jalali_day = gregorian_to_jalali(
            local.year, local.month, local.day
        )
    except (TypeError, ValueError, OverflowError):
        return ""
    weekdays = {
        "Monday": "دوشنبه", "Tuesday": "سه‌شنبه", "Wednesday": "چهارشنبه",
        "Thursday": "پنجشنبه", "Friday": "جمعه", "Saturday": "شنبه", "Sunday": "یکشنبه",
    }
    months = {
        1: "فروردین", 2: "اردیبهشت", 3: "خرداد", 4: "تیر",
        5: "مرداد", 6: "شهریور", 7: "مهر", 8: "آبان",
        9: "آذر", 10: "دی", 11: "بهمن", 12: "اسفند",
    }
    rendered = (
        f"{weekdays.get(local.strftime('%A'), '')} {jalali_day} "
        f"{months[jalali_month]} {jalali_year}، ساعت {local:%H:%M}"
    )
    return rendered.translate(str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))


def to_persian_digits(value) -> str:
    """Render ASCII digits with Persian digits and thousands separators."""
    return str(value).translate(str.maketrans("0123456789,", "۰۱۲۳۴۵۶۷۸۹٬"))


def format_persian_number(value) -> str:
    """Format an integer using Persian digits and the Persian thousands separator."""
    return to_persian_digits(f"{int(value):,}")


def unicode_strikethrough(value: str) -> str:
    """Render a visible strike-through without relying on a platform's text-markup parser."""
    overlay = "\u0336"
    return "".join(char if char.isspace() else char + overlay for char in str(value))


def unicode_underline(value: str) -> str:
    """Render an underline for Bale clients without relying on undocumented markup."""
    overlay = "\u0332"
    return "".join(char if char.isspace() else char + overlay for char in str(value))


def format_remaining_time(value, now: datetime | None = None) -> str:
    """Render the remaining offer time in Persian hours/minutes, rounded up to a minute."""
    deadline = _parse_utc_datetime(value)
    if deadline is None:
        return ""
    current = now or datetime.now(timezone.utc)
    if current.tzinfo is None:
        current = current.replace(tzinfo=timezone.utc)
    current = current.astimezone(timezone.utc)
    remaining_seconds = (deadline - current).total_seconds()
    if remaining_seconds <= 0:
        return "مهلت آفر به پایان رسیده"
    remaining_minutes = max(1, math.ceil(remaining_seconds / 60))
    hours, minutes = divmod(remaining_minutes, 60)
    duration = []
    if hours:
        duration.append(f"{format_persian_number(hours)} ساعت")
    if minutes:
        duration.append(f"{format_persian_number(minutes)} دقیقه")
    return f"{' و '.join(duration)} مانده به پایان تخفیف"


def _escape_bale_markdown(value: str) -> str:
    """Escape characters that could change Bale's documented Markdown formatting."""
    return re.sub(r"([\\_*()\[\]])", lambda match: "\\" + match.group(1), str(value or ""))


def build_caption(
    p: dict,
    affiliate_url: str,
    channel_label: str = TELEGRAM_CHANNEL_URL,
    use_unicode_strikethrough: bool = False,
) -> str:
    """Build a caption with the full featured-price and discount phrases bold-underlined, a channel-only link, and a live hours/minutes countdown."""
    is_bale = use_unicode_strikethrough

    def bold(value: str) -> str:
        return f"*{value}*" if is_bale else f"<b>{value}</b>"

    raw_title = (p.get("title") or "پیشنهاد ویژه").strip()
    raw_title = to_persian_digits(raw_title)
    if len(raw_title) > 140:
        raw_title = raw_title[:137].rstrip() + "…"
    title = _escape_bale_markdown(raw_title) if is_bale else html.escape(raw_title)

    current = p.get("current_price")
    original = p.get("original_price")
    discount = p.get("discount_percent")
    expiry = format_remaining_time(p.get("deal_expires_at"), now=p.get("_countdown_now"))

    channel_url = str(channel_label or (BALE_CHANNEL_URL if is_bale else TELEGRAM_CHANNEL_URL)).strip()
    if not urlsplit(channel_url).scheme:
        channel_url = "https://" + channel_url
    channel_href = html.escape(channel_url, quote=True)
    channel_text = "عضویت در کانال OfferChin"
    if is_bale:
        channel_footer = f"[{channel_text}]({html.unescape(channel_href)})"
    else:
        channel_footer = f'<a href="{channel_href}">{channel_text}</a>'

    parts = [
        bold("🔥 پیشنهاد شگفت‌انگیز دیجی‌کالا"),
        "",
        bold(f"🛍️ {title}"),
        "",
    ]
    if current:
        price = format_persian_number(current)
        if is_bale:
            parts.append(bold(unicode_underline(f"💚 قیمت ویژه: 💰 {price} تومان")))
        else:
            parts.append(f"<b><u>💚 قیمت ویژه: 💰 {price} تومان</u></b>")
    if discount is not None and int(discount) > 0:
        discount_value = format_persian_number(discount) + "٪"
        if is_bale:
            parts.append(bold(unicode_underline(f"⚡️ {discount_value} تخفیف")))
        else:
            parts.append(f"<b><u>⚡️ {discount_value} تخفیف</u></b>")
    if original and current and int(original) > int(current):
        original_amount = format_persian_number(original)
        if is_bale:
            original_amount = unicode_strikethrough(original_amount)
            parts += ["", bold(f"🏷️ قیمت اصلی: {original_amount} تومان")]
        else:
            parts += ["", f"<b>🏷️ قیمت اصلی: <s>{original_amount} تومان</s></b>"]
    if expiry:
        parts += ["", bold(f"⏳ {expiry}")]

    detail_line = bold("👇 برای دیدن جزئیات، دکمهٔ زیر رو بزن.")
    parts += ["", channel_footer, "", detail_line]
    caption = "\n".join(parts)
    footer = f"\n\n{channel_footer}\n\n{detail_line}"
    if len(caption) > 1024:
        body = "\n".join(parts[:-4])
        caption = body[:1024 - len(footer)].rstrip() + footer
    return caption

def format_discount_badge(discount_percent) -> str:
    """Return the visual discount badge label in concise English, e.g. '81% OFF'."""
    try:
        discount = int(discount_percent)
    except (TypeError, ValueError):
        return ""
    return f"{discount}% OFF" if 0 < discount <= 100 else ""


def build_discount_image(image_bytes: bytes, discount_percent=None, watermark: str = "Telegram.me/OfferChin") -> bytes:
    """Prepare a channel-specific product image with a discount badge and brand watermark."""
    from io import BytesIO
    with Image.open(BytesIO(image_bytes)) as raw:
        raw.load()
        image = raw.convert("RGB")
    image.thumbnail((1600, 1600), Image.Resampling.LANCZOS)
    label = format_discount_badge(discount_percent)
    draw = ImageDraw.Draw(image)
    if label:
        width, height = image.size
        font_size = max(20, min(width, height) // 16)
        font = _latin_font(font_size)
        bbox = draw.textbbox((0, 0), label, font=font)
        text_width = max(1, bbox[2] - bbox[0])
        text_height = max(font_size, bbox[3] - bbox[1])
        pad = max(10, min(width, height) // 45)
        badge_width = text_width + pad * 2
        badge_height = text_height + pad * 2
        margin = max(10, min(width, height) // 35)
        right = width - margin
        top = margin
        left = max(0, right - badge_width)
        bottom = min(height, top + badge_height)
        draw.rounded_rectangle(
            (left, top, right, bottom),
            radius=max(10, pad),
            fill="#16a34a",
            outline="#ffffff",
            width=max(2, min(width, height) // 300),
        )
        # Keep the English label left-to-right; do not apply Persian bidi shaping.
        draw.text((right - pad, top + pad), label, font=font, fill="#ffffff", anchor="ra")

    # Permanent channel watermark at lower-left for brand recognition when images are reshared.
    width, height = image.size
    watermark = str(watermark or "Telegram.me/OfferChin").strip()
    watermark_font = _latin_font(max(12, min(width, height) // 34))
    watermark_box = draw.textbbox((0, 0), watermark, font=watermark_font)
    watermark_width = watermark_box[2] - watermark_box[0]
    watermark_height = max(watermark_font.size, watermark_box[3] - watermark_box[1])
    watermark_pad = max(7, min(width, height) // 80)
    watermark_margin = max(10, min(width, height) // 35)
    watermark_left = watermark_margin
    watermark_top = max(0, height - watermark_margin - watermark_height - 2 * watermark_pad)
    watermark_right = min(width, watermark_left + watermark_width + 2 * watermark_pad)
    watermark_bottom = min(height, watermark_top + watermark_height + 2 * watermark_pad)
    draw.rounded_rectangle(
        (watermark_left, watermark_top, watermark_right, watermark_bottom),
        radius=max(6, watermark_pad),
        fill="#17251D",
        outline="#ffffff",
        width=max(1, min(width, height) // 500),
    )
    draw.text(
        (watermark_left + watermark_pad, watermark_top + watermark_pad),
        watermark,
        font=watermark_font,
        fill="#ffffff",
    )
    output = BytesIO()
    image.save(output, format="JPEG", quality=92, optimize=True)
    return output.getvalue()


def _fetch_image(url: str) -> bytes:
    if not url or urlsplit(url).scheme != "https":
        raise RuntimeError("No safe HTTPS product image URL")
    response = SESSION.get(url, timeout=HTTP_TIMEOUT, stream=True)
    response.raise_for_status()
    content_type = response.headers.get("Content-Type", "").lower()
    if not content_type.startswith("image/"):
        response.close()
        raise RuntimeError("product image URL did not return an image")
    parts, total = [], 0
    for chunk in response.iter_content(64 * 1024):
        if not chunk:
            continue
        total += len(chunk)
        if total > 10_000_000:
            response.close()
            raise RuntimeError("product image exceeded 10 MB")
        parts.append(chunk)
    response.close()
    data = b"".join(parts)
    from io import BytesIO
    with Image.open(BytesIO(data)) as check:
        check.verify()
    return data


