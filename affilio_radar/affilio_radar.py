def _fetch_image(url: str) -> bytes:
    if not url or urlsplit(url).scheme != "https":
        raise RuntimeError("No safe HTTPS product image URL")
    response = SESSION.get(url, timeout=HTTP_TIMEOUT, stream=True)
    response.raise_for_status()
    content_type = response.headers.get("Content-Type", "").lower()
    if not content_type.startswith("image/"):
        response.close()
        raise RuntimeError("product image URL did not return an image")
    parts, total = [], 0
    for chunk in response.iter_content(64 * 1024):
        if not chunk:
            continue
        total += len(chunk)
        if total > 10_000_000:
            response.close()
            raise RuntimeError("product image exceeded 10 MB")
        parts.append(chunk)
    response.close()
    data = b"".join(parts)
    from io import BytesIO
    with Image.open(BytesIO(data)) as check:
        check.verify()
    return data


def _send_video(path: Path, caption: str):
    if not BOT_TOKEN:
        raise RuntimeError("Missing TELEGRAM_BOT_TOKEN secret; no post sent")
    endpoint = f"https://api.telegram.org/bot{BOT_TOKEN}/sendVideo"
    with path.open("rb") as media:
        response = requests.post(
            endpoint,
            data={
                "chat_id": TARGET_CHAT,
                "caption": caption,
                "parse_mode": "HTML",
                "supports_streaming": "true",
            },
            files={"video": (path.name, media, "video/mp4")},
            timeout=(20, 180),
        )
    response.raise_for_status()
    payload = response.json()
    if not payload.get("ok"):
        raise RuntimeError("Telegram sendVideo returned ok=false")
    return payload["result"]


def _last_post_timestamp(state):
    try:
        previous = datetime.fromisoformat(str(state.get("last_published_at", "")))
        if previous.tzinfo is None:
            previous = previous.replace(tzinfo=timezone.utc)
        return previous.timestamp()
    except (TypeError, ValueError):
        return 0.0


def run(publish=False):
    print("Affilio radar: independent from Dayan and TrendsUploader.")
    print("Ranking is a transparent heuristic (category + affordability + visible discount + reviews), not a guarantee of sales.")
    catalog = load_catalog()
    approved = link_map(catalog)
    print(f"approved_affiliate_links={len(approved)}")
    urls, search_diagnostics = discover_product_urls()
    print(f"discovered_product_urls={len(urls)}")

    products = []
    for url in urls:
        try:
            canonical = safe_product_url(url)
            if not canonical:
                print("PRODUCT_SKIP invalid_product_url")
                continue
            item = fetch_product_record(canonical)
            if not item.get("title"):
                print(f"PRODUCT_SKIP id={item.get('product_id')} reason=no_title")
                continue
            item = score_product(item)
            item["has_affiliate_link"] = bool(approved.get(item["product_id"]))
            item["affiliate_url"] = approved.get(item["product_id"], {}).get("affiliate_url", "")
            products.append(item)
            print(
                f"PRODUCT id={item['product_id']} stock={item['availability']} "
                f"price={item.get('current_price')} rating={item.get('rating')} reviews={item.get('review_count')} "
                f"score={item['demand_score']} linked={item['has_affiliate_link']} title={item['title']!r}"
            )
        except Exception as exc:
            print(f"PRODUCT_FETCH_FAILED url={url} error={type(exc).__name__}")

    products.sort(key=lambda p: (p["demand_score"], p.get("review_count", 0)), reverse=True)
    eligible = [p for p in products if p.get("has_affiliate_link") and is_publish_eligible(p)]
    print(f"ranked_products={len(products)} publish_eligible={len(eligible)}")
    for rank, item in enumerate(products[:12], start=1):
        print(
            f"RANK {rank}: score={item['demand_score']} stock={item['availability']} "
            f"linked={item['has_affiliate_link']} price={item.get('current_price')} "
            f"title={item['title']!r} url={item['product_url']}"
        )

    report = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "ranking_note": "Heuristic only; categories, price band, public rating/review count and listed discount are signals, not proof of sales volume.",
        "search_diagnostics": search_diagnostics,
        "products": products[:40],
    }
    save_json(REPORT, report)
    state = load_state()
    state.setdefault("published", {})
    state.setdefault("last_published_at", "")
    now = time.time()
    last_post = _last_post_timestamp(state)
    cooldown_remaining = MIN_POST_INTERVAL_HOURS * 3600 - (now - last_post)
    if cooldown_remaining > 0:
        print(f"POST_COOLDOWN remaining_minutes={int(cooldown_remaining / 60)}")

    if not publish:
        print("DRY_RUN: discovery and stock checks only; no Telegram post attempted.")
    elif not BOT_TOKEN:
        print("PUBLISH_BLOCKED: TELEGRAM_BOT_TOKEN is missing; no post attempted.")
    elif cooldown_remaining > 0:
        print("PUBLISH_BLOCKED: global posting cooldown active.")
    else:
        sent = 0
        for item in eligible:
            if sent >= MAX_POSTS_PER_RUN:
                break
            pid = item["product_id"]
            old = state["published"].get(pid, {})
            try:
                last_ts = float(old.get("ts", 0))
            except (TypeError, ValueError):
                last_ts = 0
            if now - last_ts < PRODUCT_COOLDOWN_DAYS * 86400:
                print(f"PUBLISH_SKIP id={pid} reason=product_cooldown")
                continue
            try:
                image_bytes = _fetch_image(item["image_url"])
                with tempfile.TemporaryDirectory(prefix="affilio-publish-") as td:
                    video_path = Path(td) / f"{pid}.mp4"
                    build_promo_video(item, image_bytes, video_path)
                    result = _send_video(video_path, build_caption(item, item["affiliate_url"]))
                state["published"][pid] = {
                    "ts": now,
                    "title": item["title"],
                    "product_url": item["product_url"],
                    "telegram_message_id": result.get("message_id"),
                }
                state["last_published_at"] = datetime.now(timezone.utc).isoformat()
                save_json(STATE, state)
                print(f"PUBLISHED id={pid} message_id={result.get('message_id')} score={item['demand_score']}")
                sent += 1
            except Exception as exc:
                print(f"PUBLISH_FAILED id={pid} error={type(exc).__name__}")
        print(f"posts_sent={sent}")

    # Limit retained product history while preserving most recent entries.
    if isinstance(state.get("published"), dict) and len(state["published"]) > 2000:
        state["published"] = dict(sorted(state["published"].items(), key=lambda kv: float(kv[1].get("ts", 0)))[-2000:])
    if publish:
        save_json(STATE, state)
    return 0 if products or any(d.get("ok") for d in search_diagnostics) else 2


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--publish", action="store_true", help="publish at most one eligible item if all checks pass")
    parser.add_argument("--dry-run", action="store_true", help="force discovery-only mode")
    args = parser.parse_args()
    publish = (AUTOPUBLISH or args.publish) and not args.dry_run
    sys.exit(run(publish=publish))


