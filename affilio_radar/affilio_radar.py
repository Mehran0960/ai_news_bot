def _fetch_image(url: str) -> bytes:
    if not url or urlsplit(url).scheme != "https":
        raise RuntimeError("No safe HTTPS product image URL")
    response = SESSION.get(url, timeout=HTTP_TIMEOUT, stream=True)
    response.raise_for_status()
    content_type = response.headers.get("Content-Type", "").lower()
    if not content_type.startswith("image/"):
        response.close()
        raise RuntimeError("product image URL did not return an image")
    parts, total = [], 0
    for chunk in response.iter_content(64 * 1024):
        if not chunk:
            continue
        total += len(chunk)
        if total > 10_000_000:
            response.close()
            raise RuntimeError("product image exceeded 10 MB")
        parts.append(chunk)
    response.close()
    data = b"".join(parts)
    from io import BytesIO
    with Image.open(BytesIO(data)) as check:
        check.verify()
    return data


def _send_video(path: Path, caption: str):
    if not BOT_TOKEN:
        raise RuntimeError("Missing TELEGRAM_BOT_TOKEN secret; no post sent")
    endpoint = f"https://api.telegram.org/bot{BOT_TOKEN}/sendVideo"
    with path.open("rb") as media:
        response = requests.post(
            endpoint,
            data={
                "chat_id": TARGET_CHAT,
                "caption": caption,
                "parse_mode": "HTML",
                "supports_streaming": "true",
            },
            files={"video": (path.name, media, "video/mp4")},
            timeout=(20, 180),
        )
    response.raise_for_status()
    payload = response.json()
    if not payload.get("ok"):
        raise RuntimeError("Telegram sendVideo returned ok=false")
    return payload["result"]


