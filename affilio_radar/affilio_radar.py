def normalize_digits(value: str) -> str:
    return (value or "").translate(str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩٬٫", "01234567890123456789,."))


def safe_product_url(raw: str) -> str:
    try:
        p = urlsplit((raw or "").strip())
    except Exception:
        return ""
    host = (p.hostname or "").lower()
    if p.scheme not in {"http", "https"} or not (host == "digikala.com" or host.endswith(".digikala.com")):
        return ""
    match = re.search(r"/product/(dkp-\d+)", p.path, re.I)
    if not match:
        return ""
    return f"https://www.digikala.com/product/{match.group(1).lower()}/"


def product_id(url: str) -> str:
    match = re.search(r"/product/(dkp-\d+)", url or "", re.I)
    return match.group(1).lower() if match else ""


AFFILIO_URL_PLACEHOLDER = "{YOUR_BASE64_ENCODED_URL}"


def _build_direct_affilio_link(canonical: str) -> str:
    """Build the direct DigiKala URL form shown in the user's confirmed final link.

    The product path is canonicalized separately; publisher/media tracking
    parameters come from the user's own URL. Do not synthesize or randomize affid.
    """
    if (
        not canonical
        or not re.fullmatch(r"\d+", AFFILIO_UTM_SOURCE)
        or not re.fullmatch(r"\d+", AFFILIO_UTM_ID)
        or AFFILIO_UTM_MEDIUM != "Affilio"
    ):
        return ""
    try:
        decoded_affid = base64.b64decode(AFFILIO_DIGIKALA_AFFID, validate=True).decode("ascii")
    except (ValueError, UnicodeDecodeError):
        return ""
    if not re.fullmatch(r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}", decoded_affid):
        return ""
    parts = urlsplit(canonical)
    query = urlencode([
        ("utm_source", AFFILIO_UTM_SOURCE),
        ("utm_medium", AFFILIO_UTM_MEDIUM),
        ("utm_id", AFFILIO_UTM_ID),
        ("affid", AFFILIO_DIGIKALA_AFFID),
    ])
    return urlunsplit((parts.scheme, parts.netloc, parts.path, query, ""))


def build_affilio_tracking_link(product_url: str, template: str | None = None) -> str:
    """Build an affiliate URL using the user's verified DigiKala tracking pattern.

    If an official reusable Affilio tracking template is configured, it remains
    supported. Otherwise use the direct URL parameters from the user's own final
    DigiKala URL; no per-product link or extra GitHub secret is required.
    """
    canonical = safe_product_url(product_url)
    if not canonical:
        return ""
    template = (template if template is not None else AFFILIO_LINK_TEMPLATE).strip()
    if not template:
        return _build_direct_affilio_link(canonical)
    if template.count(AFFILIO_URL_PLACEHOLDER) != 1:
        return ""
    try:
        parsed = urlsplit(template)
    except Exception:
        return ""
    host = (parsed.hostname or "").lower()
    if (
        parsed.scheme != "https"
        or host != "migmig.affilio.ir"
        or "/api/v1/click/b/" not in parsed.path.lower()
        or any(ch in template for ch in ("\n", "\r", "\t", " "))
    ):
        return ""
    encoded = base64.b64encode(canonical.encode("utf-8")).decode("ascii")
    result = template.replace(AFFILIO_URL_PLACEHOLDER, encoded)
    try:
        built = urlsplit(result)
    except Exception:
        return ""
    if (
        built.scheme != "https"
        or (built.hostname or "").lower() != "migmig.affilio.ir"
        or "/api/v1/click/b/" not in built.path.lower()
        or AFFILIO_URL_PLACEHOLDER in result
    ):
        return ""
    return result


def _walk_dicts(value):
    if isinstance(value, dict):
        yield value
        for child in value.values():
            yield from _walk_dicts(child)
    elif isinstance(value, list):
        for child in value:
            yield from _walk_dicts(child)


def _as_list(value):
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def _money_to_toman(raw, currency=""):
    if raw is None:
        return None
    raw_s = normalize_digits(str(raw)).strip().replace(",", "").replace("٬", "").replace("٫", ".")
    match = re.search(r"\d+(?:\.\d+)?", raw_s)
    if not match:
        return None
    try:
        amount = float(match.group(0))
    except ValueError:
        return None
    currency = str(currency or "").upper()
    # JSON-LD may express Iranian prices in IRR (rials), while visible page/meta
    # values are usually already in toman. Convert only when currency says IRR.
    if currency == "IRR":
        amount /= 10
    result = int(round(amount))
    return result if result >= 1000 else None


def _clean_title(value):
    value = BeautifulSoup(str(value or ""), "html.parser").get_text(" ", strip=True)
    value = re.sub(r"\s+", " ", html.unescape(value)).strip()
    value = re.sub(r"\s*[|–-]\s*(?:دیجی ?کالا|خرید|قیمت).*$", "", value, flags=re.I)
    return value[:180]


def _availability_from_page(soup, product_obj=None):
    # Structured product/offer fields are more reliable than generic page text.
    for obj in [product_obj] if isinstance(product_obj, dict) else []:
        offers = _as_list(obj.get("offers"))
        for offer in offers:
            if not isinstance(offer, dict):
                continue
            availability = str(offer.get("availability", "")).lower().rsplit("/", 1)[-1]
            availability = availability.replace("_", "").replace("-", "")
            if availability in {"outofstock", "soldout", "discontinued", "preorder"}:
                return "out_of_stock", "schema.org"
            if availability in {"instock", "limitedavailability", "onlineonly"}:
                return "in_stock", "schema.org"

    # Some pages expose non-schema stock keys in serialized page data.
    raw_html = str(soup)
    low = raw_html.lower()
    if re.search(r'"(?:stockquantity|inventoryquantity|availablequantity)"\s*:\s*0(?:\D|$)', low):
        return "out_of_stock", "page_data_quantity"
    for key in ("\"hasstock\":false", "\"isavailable\":false", "\"available\":false"):
        if key in low:
            return "out_of_stock", "page_data_flag"
    for key in ("\"hasstock\":true", "\"isavailable\":true", "\"available\":true"):
        if key in low:
            return "in_stock", "page_data_flag"

    text = re.sub(r"\s+", " ", soup.get_text(" ", strip=True)).lower()
    text = text.replace("ي", "ی").replace("ك", "ک")
    if any(term in text for term in (
        "اتمام موجودی", "ناموجود", "موجودی ندارد", "موجود نیست",
        "قابل سفارش نیست", "out of stock", "sold out", "unavailable",
    )):
        return "out_of_stock", "visible_text"
    if any(term in text for term in (
        "موجود در انبار", "در انبار موجود است", "قابل سفارش",
        "افزودن به سبد خرید", "in stock",
    )):
        # The page must state a positive signal explicitly; mere existence of a
        # generic "buy" word is not enough.
        if "قابل سفارش نیست" not in text:
            return "in_stock", "visible_text"
    return "unknown", "no_reliable_stock_signal"


def parse_product_page(url: str, page_html: str) -> dict:
    soup = BeautifulSoup(page_html or "", "html.parser")
    meta = {}
    for node in soup.select("meta"):
        key = (node.get("property") or node.get("name") or node.get("itemprop") or "").strip().lower()
        content = node.get("content")
        if key and content:
            meta[key] = html.unescape(content.strip())

    product_obj = None
    for node in soup.select('script[type="application/ld+json"]'):
        try:
            data = json.loads(node.string or node.get_text())
        except (ValueError, TypeError):
            continue
        for obj in _walk_dicts(data):
            types = obj.get("@type", [])
            if isinstance(types, str):
                types = [types]
            if any(str(t).lower() == "product" for t in types) and (obj.get("name") or obj.get("offers")):
                product_obj = obj
                break
        if product_obj:
            break

    title = ""
    image = ""
    current_price = None
    original_price = None
    rating = None
    review_count = 0
    currency = ""

    if product_obj:
        title = _clean_title(product_obj.get("name"))
        images = _as_list(product_obj.get("image"))
        if images and isinstance(images[0], str):
            image = images[0]
        offers = _as_list(product_obj.get("offers"))
        for offer in offers:
            if not isinstance(offer, dict):
                continue
            currency = str(offer.get("priceCurrency", currency or ""))
            value = _money_to_toman(offer.get("price") or offer.get("lowPrice"), currency)
            if value and (current_price is None or value < current_price):
                current_price = value
            specs = _as_list(offer.get("priceSpecification"))
            for spec in specs:
                if not isinstance(spec, dict):
                    continue
                spec_value = _money_to_toman(spec.get("price"), currency)
                type_text = " ".join(str(spec.get(k, "")) for k in ("priceType", "name", "@type")).lower()
                if spec_value and any(k in type_text for k in ("list", "regular", "strike", "original", "high")):
                    original_price = max(original_price or 0, spec_value)
        aggregate = product_obj.get("aggregateRating")
        if isinstance(aggregate, dict):
            try:
                rating = float(normalize_digits(str(aggregate.get("ratingValue", ""))))
            except ValueError:
                rating = None
            try:
                review_count = int(float(normalize_digits(str(aggregate.get("reviewCount") or aggregate.get("ratingCount") or 0))))
            except ValueError:
                review_count = 0

    title = title or _clean_title(meta.get("og:title") or meta.get("twitter:title") or meta.get("title") or "")
    if not title:
        h1 = soup.find("h1")
        title = _clean_title(h1.get_text(" ", strip=True) if h1 else "")
    image = image or meta.get("og:image") or meta.get("twitter:image") or meta.get("twitter:image:src") or ""
    image = urljoin(url, image) if image else ""

    if current_price is None:
        for key in ("product:price:amount", "og:price:amount", "product:price", "price"):
            if meta.get(key):
                current_price = _money_to_toman(meta[key], meta.get("product:price:currency") or meta.get("pricecurrency") or "")
                if current_price:
                    break

    if original_price is None:
        for key in ("product:original_price", "product:price:standard_amount", "og:price:standard_amount", "price:regular"):
            if meta.get(key):
                original_price = _money_to_toman(meta[key], meta.get("product:price:currency") or "")
                if original_price:
                    break

    # Public page text as a limited fallback, only when it contains explicit toman labels.
    visible = soup.get_text(" ", strip=True)
    visible_norm = normalize_digits(visible).replace("٬", ",").replace("،", ",")
    explicit_prices = []
    for match in re.finditer(r"(?<!\d)(\d{1,3}(?:,\d{3})+|\d{4,})(?!\d)\s*(?:تومان|تومن)", visible_norm):
        amount = _money_to_toman(match.group(1))
        if amount:
            explicit_prices.append(amount)
    explicit_prices = list(dict.fromkeys(explicit_prices))
    if current_price is None and explicit_prices:
        current_price = explicit_prices[0]
    if original_price is None and len(explicit_prices) > 1:
        original_price = max(explicit_prices)

    if current_price and original_price and original_price <= current_price:
        original_price = None
    availability, availability_source = _availability_from_page(soup, product_obj)
    return {
        "product_id": product_id(url),
        "product_url": safe_product_url(url),
        "title": title,
        "image_url": image,
        "current_price": current_price,
        "original_price": original_price,
        "rating": rating,
        "review_count": max(0, review_count),
        "availability": availability,
        "availability_source": availability_source,
        "checked_at": datetime.now(timezone.utc).isoformat(),
    }


def fetch_page(url: str):
    response = SESSION.get(url, timeout=HTTP_TIMEOUT, allow_redirects=True)
    response.raise_for_status()
    if len(response.content) > 5_000_000:
        raise RuntimeError("Page exceeded 5 MB safety limit")
    return response.url, response.text


